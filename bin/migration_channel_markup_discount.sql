-- 百分比格式，如 5 表示 5%；0 表示无加价；NULL 按 0 处理
-- 兼容 MySQL、PostgreSQL、SQLite
--
-- MySQL / SQLite（执行此行）:
ALTER TABLE channels ADD COLUMN markup_discount_rate DOUBLE PRECISION DEFAULT 0 COMMENT '加价折扣率（百分比%），0=无加价';
